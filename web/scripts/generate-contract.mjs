// Generates TypeScript types from ../schema/*.schema.json into src/contract/.
//
// One file per schema (looping instead of relying on json2ts globbing), plus an
// index.ts barrel. Shared types (Developer, Resource, ...) are repeated in the
// files that reference them, so the barrel re-exports each name once, from the
// smallest file that declares it (the schema that owns it).
//
// Run with `npm run generate`. The output is committed; CI checks it is current.
import { readdir, readFile, writeFile, mkdir, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const schemaDir = path.resolve(here, "../../schema");
const outDir = path.resolve(here, "../src/contract");

const banner = `/* eslint-disable */
// Code generated by \`npm run generate\` from schema/*.schema.json. DO NOT EDIT.`;

const files = (await readdir(schemaDir))
  .filter((f) => f.endsWith(".schema.json"))
  .sort();

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const declared = new Map(); // type name -> [{ module, count }]

for (const file of files) {
  const schema = JSON.parse(await readFile(path.join(schemaDir, file), "utf8"));
  const ts = await compile(schema, schema.title ?? file, {
    cwd: schemaDir,
    additionalProperties: false,
    bannerComment: banner,
    style: { singleQuote: false, semi: true, printWidth: 100 },
  });
  const moduleName = file.replace(/\.schema\.json$/, "");
  await writeFile(path.join(outDir, `${moduleName}.ts`), ts);

  const names = [...ts.matchAll(/^export (?:interface|type) (\w+)/gm)].map((m) => m[1]);
  for (const name of names) {
    const list = declared.get(name) ?? [];
    list.push({ module: moduleName, count: names.length });
    declared.set(name, list);
  }
}

const byModule = new Map();
for (const [name, list] of [...declared].sort(([a], [b]) => a.localeCompare(b))) {
  list.sort((a, b) => a.count - b.count || a.module.localeCompare(b.module));
  const owner = list[0].module;
  byModule.set(owner, [...(byModule.get(owner) ?? []), name]);
}

const lines = [banner, ""];
for (const [mod, names] of [...byModule].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`export type { ${names.join(", ")} } from "./${mod}";`);
}
await writeFile(path.join(outDir, "index.ts"), lines.join("\n") + "\n");

console.log(`generated ${files.length} contract files + index.ts in src/contract/`);
