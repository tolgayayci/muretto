// ---- YAML node helpers ----

func mapping() *yaml.Node { return &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"} }

func flow(n *yaml.Node) *yaml.Node { n.Style = yaml.FlowStyle; return n }

func add(m *yaml.Node, key string, v *yaml.Node) *yaml.Node {
	k := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: key}
	m.Content = append(m.Content, k, v)
	return k
}

func str(v string) *yaml.Node {
	n := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v}
	if strings.Contains(v, "\n") {
		n.Style = yaml.LiteralStyle
	}
	return n
}

func quoted(v string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v, Style: yaml.SingleQuotedStyle}
}

func intNode(v int) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: fmt.Sprint(v)}
}

func seq(vs ...*yaml.Node) *yaml.Node {
	return &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq", Content: vs}
}

func strSeq(vs []string) *yaml.Node {
	n := seq()
	for _, v := range vs {
		n.Content = append(n.Content, str(v))
	}
	return flow(n)
}

func regexSeq(vs ...string) *yaml.Node {
	n := seq()
	for _, v := range vs {
		n.Content = append(n.Content, quoted(v))
	}
	return flow(n)
}

// plainText makes spec prose safe for templates (braces are placeholders)
// and keeps it short.
func plainText(s string, max int) string {
	s = strings.NewReplacer("{", "(", "}", ")", "\r", "").Replace(strings.TrimSpace(s))
	s = regexp.MustCompile(`\s+`).ReplaceAllString(s, " ")
	if len(s) > max {
		s = strings.TrimSpace(s[:max]) + "..."
	}
	return s
}

var reTmplSafe = regexp.MustCompile(`^[A-Za-z0-9_$@-]+$`)

// ---- emit ----

func (g *gen) emit(sel []*col) ([]byte, error) {
	root := mapping()
	k := add(root, "format", intNode(1))
	spec := g.opt.SpecName
	if spec == "" {
		spec = "an OpenAPI description"
	}
	k.HeadComment = strings.Join([]string{
		fmt.Sprintf("%s adapter, generated by `muretto adapter new` from %s", g.display, spec),
		fmt.Sprintf("(%s). Every endpoint and field below comes from that spec.", g.rep.Spec),
		"Draft: check every line marked REVIEW, then run `muretto adapter check`.",
		"Format: adapters/WRITING.md",
	}, "\n")
	add(root, "provider", str(g.slug))
	add(root, "display_name", str(g.display))
	api := mapping()
	add(api, "base_url", str("https://"+g.host))
	auth := flow(mapping())
	add(auth, "header", str(g.authH))
	if g.authS != "" {
		add(auth, "scheme", str(g.authS))
	}
	add(api, "auth", auth)
	add(root, "api", api)
	if g.opt.MCPServer != "" {
		k := add(root, "mcp_servers", strSeq([]string{g.opt.MCPServer}))
		k.HeadComment = "REVIEW: MCP signatures assume this server names its tools after operationIds."
	}
	add(root, "token_help", str(g.tokenHelp()+"\n"))

	endpoints := mapping()
	epNames := map[string]bool{}
	for _, c := range sel {
		epNames[c.kind] = true
	}
	acctEP := ""
	if !g.acct.none && g.acct.ask == "" {
		acctEP = "accounts"
		if epNames[acctEP] {
			acctEP = "account_list"
		}
		ep := mapping()
		add(ep, "path", str(g.acct.op.path))
		if strip := stripPaths(g.acct.op.op.Success().Schema); len(strip) > 0 {
			add(ep, "strip", strSeq(strip))
		}
		kk := add(endpoints, acctEP, ep)
		kk.HeadComment = opComment(g.acct.op)
	}

	kinds := seq()
	var rules []*yaml.Node
	var sigs []*yaml.Node
	for _, c := range sel {
		g.prepare(c)
		ep, err := g.endpoint(c)
		if err != nil {
			return nil, err
		}
		kk := add(endpoints, c.kind, ep)
		kk.HeadComment = opComment(c.opInfo)
		kr, ruleIDs := g.rules(c)
		rules = append(rules, kr...)
		kinds.Content = append(kinds.Content, g.kind(c, ruleIDs))
		sigs = append(sigs, g.signatures(c)...)
	}
	add(root, "endpoints", endpoints)

	accts := mapping()
	if g.acct.ask != "" {
		kk := add(accts, "ask", str(g.acct.ask))
		kk.HeadComment = "REVIEW: no endpoint lists accounts; muretto init asks the user for this value."
	} else if g.acct.none {
		kk := add(accts, "id", str("default"))
		kk.HeadComment = "REVIEW: no org, team or current-user endpoint in the spec; one account per token."
		add(accts, "name", str(g.display))
	} else {
		add(accts, "endpoint", str(acctEP))
		add(accts, "items", str(g.acct.items[0]))
		add(accts, "id", str("{"+g.acct.idF+"}"))
		if g.acct.nameF != "" {
			add(accts, "name", str("{"+g.acct.nameF+"}"))
		}
		if g.acct.slugF != "" {
			add(accts, "slug", str("{"+g.acct.slugF+"}"))
		}
	}
	add(root, "accounts", accts)
	if !g.acct.none && g.acct.ask == "" && g.acct.idF == "slug" {
		add(root, "account_slug", str("{account}"))
	}
	add(root, "kinds", kinds)
	if len(rules) > 0 {
		add(root, "rules", seq(rules...))
	}
	if len(sigs) > 0 {
		add(root, "signatures", seq(sigs...))
	}
	add(root, "coverage", g.coverage(sel))
	add(root, "recorder", g.recorder(sel))

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func opComment(oi *opInfo) string {
	s := fmt.Sprintf("%s %s", strings.ToUpper(oi.op.Method), oi.op.Path)
	if oi.op.ID != "" {
		s += " (" + oi.op.ID + ")"
	}
	return s
}

func (g *gen) tokenHelp() string {
	var b strings.Builder
	fmt.Fprintf(&b, "Token for %s, sent as %s.", g.display, authText(g.authH, g.authS))
	if s := g.doc.SecuritySchemes[g.authNm]; s != nil {
		if s.Description != "" {
			b.WriteString("\nFrom the API description: " + plainText(s.Description, 400))
		}
		var read []string
		for name := range s.Scopes {
			if regexp.MustCompile(`(?i)read|view|list|get`).MatchString(name) {
				read = append(read, name)
			}
		}
		sort.Strings(read)
		if len(read) > 8 {
			read = read[:8]
		}
		if len(read) > 0 {
			b.WriteString("\nRead scopes in the spec: " + strings.Join(read, ", ") + ".")
		}
	}
	b.WriteString("\nUse the narrowest token the API offers (read-only if it has one). Muretto only\nsends GET requests to the endpoints listed in this file, enforced in code (internal/broker).")
	return b.String()
}

// prepare computes attribute names a kind's children and fixes rely on.
func (g *gen) prepare(c *col) {
	if c.parent != nil {
		p := c.parent
		c.ancestors = append(c.ancestors, ancestorAttr{of: p, name: refAttrName(p), tmpl: "{parent." + p.wrap + p.idField + "}"})
		for _, a := range p.ancestors {
			c.ancestors = append(c.ancestors, ancestorAttr{of: a.of, name: a.name, tmpl: "{parent." + a.name + "}"})
		}
		c.idAttr = snake(c.idField)
		if reservedAttrs[c.idAttr] {
			c.idAttr = c.kind + "_" + c.idAttr
		}
		if reservedAttrs[c.idAttr] {
			c.idAttr = c.kind + "_item_" + snake(c.idField)
		}
		for _, a := range c.ancestors {
			if a.name == c.idAttr {
				c.idAttr = c.kind + "_item_" + snake(c.idField)
			}
		}
	}
	core := map[string]bool{c.idField: true}
	if n := pickName(c.item, c.idField); n != "" && reTmplSafe.MatchString(n) {
		c.nameF, core[n] = n, true
	}
	if s := pickStatus(c.item); s != "" && reTmplSafe.MatchString(s) {
		c.statusF, core[s] = s, true
	}
	if u := pickURL(c.item); u != "" && reTmplSafe.MatchString(u) {
		c.urlF, core[u] = u, true
	}
	if f, format := pickCreated(c.item); f != "" && reTmplSafe.MatchString(f) {
		c.createdF, c.createdFmt, core[f] = f, format, true
	}
	// Ancestor ids and the raw id take their names first, so an item field
	// with the same name never shadows them.
	used := map[string]bool{}
	for _, a := range c.ancestors {
		used[a.name] = true
	}
	if c.parent != nil {
		used[c.idAttr] = true
	}
	for _, a := range pickAttrs(c.item, core) {
		if used[a.name] {
			continue
		}
		used[a.name] = true
		c.attrs = append(c.attrs, a)
	}
}

// authText describes how the token is sent, without writing a credential
// shape ("Bearer <token>") that redaction would mask.
func authText(header, scheme string) string {
	if scheme == "" {
		return "the " + header + " header"
	}
	return "a " + scheme + " token in the " + header + " header"
}

// refAttrName names the attribute children store their parent's id in.
func refAttrName(p *col) string {
	f := snake(p.idField)
	name := p.kind + "_" + f
	if strings.HasPrefix(f, p.kind+"_") {
		name = f
	}
	if reservedAttrs[name] {
		name = "parent_" + name
	}
	return name
}

func (g *gen) paramTemplate(c *col, i int) (string, bool) {
	switch o := c.owners[i].(type) {
	case acctOwner:
		return "{account}", true
	case string:
		return o, false
	case *col:
		if o == c.parent {
			return "{parent." + o.wrap + o.idField + "}", true
		}
		for _, a := range c.parent.ancestors {
			if a.of == o {
				return "{parent." + a.name + "}", true
			}
		}
	}
	return "", false
}

func (g *gen) endpoint(c *col) (*yaml.Node, error) {
	ep := mapping()
	path := c.path
	params := flow(mapping())
	pi := 0
	for _, s := range c.segs {
		if !isParam(s) {
			continue
		}
		t, isTmpl := g.paramTemplate(c, pi)
		pi++
		if !isTmpl {
			// A constant (a default or the only enum value): put it in the
			// path, so the allowlist is exact.
			path = strings.Replace(path, s, t, 1)
			continue
		}
		add(params, paramName(s), str(t))
	}
	add(ep, "path", str(path))
	if len(params.Content) > 0 {
		add(ep, "params", params)
	}
	query := flow(mapping())
	if q := g.acctQuery(c.op); q != "" {
		add(query, q, str("{account}"))
	}
	if c.viaQ != "" {
		add(query, c.viaQ, str("{parent."+c.parent.wrap+c.parent.idField+"}"))
	}
	for _, p := range c.op.Params {
		if p.In == "query" && p.Required && p.Name != c.viaQ && !g.acctParam(p.Name) {
			if v, ok := literal(p); ok {
				add(query, p.Name, str(v))
			}
		}
	}
	c.paging = detectPaging(c.op, c.resp, firstProp(c.items))
	if name, max := pageSize(c.op); name != "" && name != c.paging.param && !hasKey(query, name) {
		add(query, name, str(max))
	}
	if len(query.Content) > 0 {
		add(ep, "query", query)
	}
	if c.paging.style == "cursor" && !hasKey(query, c.paging.param) {
		pg := flow(mapping())
		add(pg, "next", str(c.paging.next))
		add(pg, "param", str(c.paging.param))
		add(ep, "pagination", pg)
	} else if c.paging.style == "cursor" {
		c.paging = paging{style: "unknown", note: "the cursor parameter is already a fixed query value"}
	}
	if strip := stripPaths(c.resp); len(strip) > 0 {
		add(ep, "strip", strSeq(strip))
	}
	return ep, nil
}

func hasKey(m *yaml.Node, k string) bool {
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == k {
			return true
		}
	}
	return false
}

func firstProp(items []string) string {
	for _, i := range items {
		if i != "$" {
			return i
		}
	}
	return ""
}

// acctQuery picks the one query parameter that carries the account id.
func (g *gen) acctQuery(op *openapi.Operation) string {
	if g.acct.none || !g.acct.orgish {
		return ""
	}
	var cands []*openapi.Param
	for _, p := range op.Params {
		if p.In == "query" && g.acctParam(p.Name) {
			cands = append(cands, p)
		}
	}
	if len(cands) == 0 {
		return ""
	}
	want := "id"
	if snake(g.acct.idF) == "slug" || snake(g.acct.idF) == "name" {
		want = snake(g.acct.idF)
	}
	sort.SliceStable(cands, func(i, j int) bool {
		si, sj := 0, 0
		if cands[i].Required {
			si += 2
		}
		if cands[j].Required {
			sj += 2
		}
		if strings.HasSuffix(snake(cands[i].Name), want) {
			si++
		}
		if strings.HasSuffix(snake(cands[j].Name), want) {
			sj++
		}
		return si > sj
	})
	return cands[0].Name
}

func (g *gen) kind(c *col, ruleIDs []string) *yaml.Node {
	k := mapping()
	add(k, "kind", str(c.kind))
	if c.parent != nil {
		add(k, "for_each", str(c.parent.kind))
	}
	src := mapping()
	add(src, "endpoint", str(c.kind))
	if len(c.items) == 1 {
		add(src, "items", str(c.items[0]))
	} else {
		add(src, "items", strSeq(c.items))
	}
	if w := g.acctFilter(c); w != nil {
		kk := add(src, "where", w)
		kk.HeadComment = "This endpoint lists every account's items: keep the scanned account's."
	}
	if len(ruleIDs) > 0 {
		add(src, "checks_rules", strSeq(ruleIDs))
	}
	w := c.wrap
	id := "{" + w + c.idField + "}"
	if c.parent != nil {
		id = "{parent.provider_id}/" + id
	}
	add(src, "id", str(id))
	switch {
	case c.nameF != "":
		add(src, "name", str("{"+w+c.nameF+"}"))
	case c.parent != nil:
		add(src, "name", str("{"+w+c.idField+"}"))
	}
	if c.statusF != "" {
		add(src, "status", str("{"+w+c.statusF+"|lower}"))
	}
	if c.urlF != "" {
		add(src, "url", str("{"+w+c.urlF+"}"))
	}
	if c.createdF != "" {
		ca := flow(mapping())
		add(ca, "value", str("{"+w+c.createdF+"}"))
		add(ca, "format", str(c.createdFmt))
		add(src, "created_at", ca)
	}
	attrs := seq()
	if c.parent != nil && !reservedAttrs[c.idAttr] {
		attrs.Content = append(attrs.Content, attrNode(c.idAttr, w+c.idField))
	}
	for _, a := range c.attrs {
		attrs.Content = append(attrs.Content, attrNode(a.name, w+a.field))
	}
	for _, a := range c.ancestors {
		m := flow(mapping())
		add(m, "name", str(a.name))
		add(m, "template", str(a.tmpl))
		attrs.Content = append(attrs.Content, m)
	}
	g.kindInfo(c).Attributes = len(attrs.Content)
	if len(attrs.Content) > 0 {
		add(src, "attributes", attrs)
	}
	add(k, "sources", seq(src))
	if c.parent != nil {
		m := flow(mapping())
		add(m, "value", str("{"+c.idAttr+"}"))
		add(m, "container", str("{"+c.ancestors[0].name+"}"))
		add(k, "match", m)
	} else {
		m := flow(mapping())
		add(m, "value", str("{provider_id}"))
		add(k, "match", m)
	}
	if fx := g.removeFix(c); fx != nil {
		add(k, "remove", fx)
		g.kindInfo(c).Remove = true
	}
	ki := g.kindInfo(c)
	switch c.paging.style {
	case "cursor":
		ki.Paging = "cursor (" + c.paging.param + ")"
	case "none":
		ki.Paging = "single page"
	default:
		ki.Paging = "first page only: " + c.paging.note
	}
	return k
}

func attrNode(name, field string) *yaml.Node {
	if name == field {
		return str(name)
	}
	m := flow(mapping())
	add(m, "name", str(name))
	add(m, "field", str(field))
	return m
}

// acctFilter keeps only the scanned account's items when an endpoint lists
// items of every account the token sees (Supabase /v1/projects).
func (g *gen) acctFilter(c *col) *yaml.Node {
	if g.acct.none || g.acct.col == nil || !g.acct.orgish || c.parent != nil {
		return nil
	}
	for _, o := range c.owners {
		if _, ok := o.(acctOwner); ok {
			return nil
		}
	}
	if g.acctQuery(c.op) != "" {
		return nil
	}
	kind := g.acct.kind
	idf := snake(g.acct.idF)
	for _, name := range []string{kind + "_" + idf, "org_" + idf, "organization_" + idf, "team_" + idf, "workspace_" + idf, "account_" + idf} {
		f, p := prop(c.item, name)
		if f != "" && c.item.Required[f] && p.Scalar() && reTmplSafe.MatchString(f) {
			m := flow(mapping())
			add(m, "field", str(c.wrap+f))
			add(m, "in_field", str("account"))
			return m
		}
	}
	return nil
}

// pathText renders an operation path for printed commands: the account,
// ancestors and the item itself as resource placeholders.
func (g *gen) pathText(c *col, oi *opInfo, item string) string {
	var b strings.Builder
	pi := 0
	nparams := countParams(oi.segs)
	for _, s := range strings.SplitAfter(oi.path, "/") {
		seg := strings.TrimSuffix(s, "/")
		if !isParam(seg) {
			b.WriteString(s)
			continue
		}
		t := "<" + paramName(seg) + ">"
		switch {
		case pi == nparams-1 && item != "":
			t = item
		case pi < len(c.owners):
			switch o := c.owners[pi].(type) {
			case acctOwner:
				t = "{account_id}"
			case string:
				t = o
			case *col:
				for _, a := range c.ancestors {
					if a.of == o {
						t = "{" + a.name + "}"
					}
				}
			}
		}
		pi++
		b.WriteString(t)
		if strings.HasSuffix(s, "/") {
			b.WriteString("/")
		}
	}
	q := []string{}
	for _, p := range oi.op.Params {
		if p.In != "query" || !p.Required {
			continue
		}
		switch {
		case g.acctParam(p.Name):
			q = append(q, p.Name+"={account_id}")
		case p.Name == c.viaQ && len(c.ancestors) > 0:
			q = append(q, p.Name+"={"+c.ancestors[0].name+"}")
		default:
			if v, ok := literal(p); ok {
				q = append(q, p.Name+"="+v)
			} else {
				q = append(q, p.Name+"=<"+p.Name+">")
			}
		}
	}
	if aq := g.acctQuery(oi.op); aq != "" && !strings.Contains(strings.Join(q, "&"), aq+"=") {
		q = append(q, aq+"={account_id}")
	}
	out := "https://" + g.host + b.String()
	if len(q) > 0 {
		out += "?" + strings.Join(q, "&")
	}
	return out
}

func (g *gen) authCurl() string {
	v := strings.TrimSpace(g.authS + " $" + g.env)
	return fmt.Sprintf(`-H "%s: %s"`, g.authH, v)
}

func (g *gen) itemRef(c *col) string {
	if c.parent == nil {
		return "{provider_id}"
	}
	return "{" + c.idAttr + "}"
}

func (g *gen) removeFix(c *col) *yaml.Node {
	del := g.findOp("delete", c.norm+"/{}")
	if del == nil {
		return nil
	}
	m := mapping()
	add(m, "kind", str("command"))
	add(m, "text", quoted(fmt.Sprintf(`curl -X DELETE "%s" %s`, g.pathText(c, del, g.itemRef(c)), g.authCurl())))
	if del.op.Summary != "" {
		add(m, "note", str("From the spec ("+del.op.ID+"): "+plainText(del.op.Summary, 200)))
	}
	return m
}

// ---- signatures ----

func pathRegex(host, path string, capture int) string {
	var b strings.Builder
	b.WriteString(regexp.QuoteMeta(host))
	pi := 0
	for _, s := range strings.SplitAfter(path, "/") {
		seg := strings.TrimSuffix(s, "/")
		if isParam(seg) {
			if pi == capture {
				b.WriteString(`(?P<parent>[^/?#\s'"]+)`)
			} else {
				b.WriteString(`[^/?#\s'"]+`)
			}
			pi++
		} else {
			b.WriteString(regexp.QuoteMeta(seg))
		}
		if strings.HasSuffix(s, "/") {
			b.WriteString("/")
		}
	}
	return b.String()
}

const rePOST = `(?:-X\s*POST\b|--request[=\s]+POST\b|\s-d[\s'"@]|\s--data(?:-raw|-binary|-urlencode)?[=\s]|\s--json[=\s])`

// createID finds where a create response carries the new item's id.
func createID(op *openapi.Operation, idField string) string {
	r := op.Success()
	if r == nil || !r.JSON || r.Schema == nil {
		return ""
	}
	s := r.Schema
	if p := s.Properties[idField]; p != nil && idLike(p) {
		return "result." + idField
	}
	for _, k := range s.Order {
		p := s.Properties[k]
		if objectLike(p) && p.Properties[idField] != nil && idLike(p.Properties[idField]) && reTmplSafe.MatchString(k) {
			return "result." + k + "." + idField
		}
	}
	return ""
}

func errorKeys(op *openapi.Operation) []string {
	success := map[string]bool{}
	if r := op.Success(); r != nil && r.Schema != nil {
		for k := range r.Schema.Properties {
			success[k] = true
		}
	}
	seen := map[string]bool{}
	var out []string
	for _, r := range op.Responses {
		if !(strings.HasPrefix(r.Code, "4") || strings.HasPrefix(r.Code, "5") || r.Code == "default") || r.Schema == nil {
			continue
		}
		for _, k := range r.Schema.Order {
			if !success[k] && !seen[k] && reTmplSafe.MatchString(k) {
				seen[k] = true
				out = append(out, k)
			}
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return errRank(out[i]) < errRank(out[j]) })
	if len(out) > 3 {
		out = out[:3]
	}
	if len(out) == 0 && !success["error"] {
		out = []string{"error"}
	}
	return out
}

func errRank(k string) int {
	switch k {
	case "error":
		return 0
	case "errors":
		return 1
	case "message":
		return 2
	case "code":
		return 3
	}
	return 9
}

func (g *gen) signatures(c *col) []*yaml.Node {
	post := g.findOp("post", c.norm)
	if post == nil {
		return nil
	}
	idPath := createID(post.op, c.idField)
	if idPath == "" {
		g.review("%s: the create operation %s returns no %s, so curl creations are not recognised", c.kind, opComment(post), c.idField)
		return nil
	}
	g.kindInfo(c).Create = true
	capture := -1
	resultContainer := ""
	if c.parent != nil && c.viaQ == "" {
		capture = countParams(post.segs) - 1
	}
	if c.parent != nil && c.viaQ != "" {
		// The parent is a query parameter of the list, not part of the POST
		// URL: attribution needs it from the create response.
		if r := post.op.Success(); r != nil && r.Schema != nil && r.Schema.Properties[c.viaQ] != nil && reTmplSafe.MatchString(c.viaQ) {
			resultContainer = "{result." + c.viaQ + "}"
		} else {
			g.review("%s: the create operation %s does not name its %s, so curl creations cannot be attributed; no signature written", c.kind, opComment(post), c.parent.kind)
			return nil
		}
	}
	var out []*yaml.Node

	// curl against the API.
	s := mapping()
	id := g.slug + ".api.create_" + c.kind
	kk := add(s, "id", str(id))
	kk.HeadComment = "curl " + opComment(post) + " (from the spec)"
	add(s, "kind", str(c.kind))
	add(s, "role", str("created"))
	when := mapping()
	add(when, "tool", quoted("^Bash$"))
	add(when, "command", regexSeq(`\bcurl\b`, pathRegex(g.host, post.path, -1)+`(?:[?#'"\s]|$)`, rePOST))
	if keys := errorKeys(post.op); len(keys) > 0 {
		add(when, "result_lacks", strSeq(keys))
	}
	add(s, "when", when)
	ex := mapping()
	add(ex, "from", str("result"))
	add(ex, "value", str("{"+idPath+"}"))
	if capture >= 0 {
		cp := flow(mapping())
		add(cp, "from", str("command"))
		add(cp, "pattern", quoted(pathRegex(g.host, post.path, capture)))
		add(ex, "capture", seq(cp))
		add(ex, "container", str("{parent}"))
	}
	if resultContainer != "" {
		add(ex, "container", str(resultContainer))
	}
	add(s, "extract", seq(ex))
	out = append(out, s)
	g.rep.Signatures = append(g.rep.Signatures, id)
	g.sigs = append(g.sigs, sigInfo{id: id, kind: c.kind, post: post, idPath: idPath, errKeys: errorKeys(post.op), col: c, capture: capture, resultParent: strings.TrimSuffix(strings.TrimPrefix(resultContainer, "{result."), "}")})

	if g.opt.MCPServer != "" && post.op.ID != "" {
		m := mapping()
		mid := g.slug + ".mcp.create_" + c.kind
		kk := add(m, "id", str(mid))
		kk.HeadComment = "REVIEW: assumes the MCP tool is named after operationId " + post.op.ID
		add(m, "kind", str(c.kind))
		add(m, "role", str("created"))
		w := flow(mapping())
		tools := []string{post.op.ID}
		if sn := snake(post.op.ID); sn != post.op.ID {
			tools = append(tools, sn)
		}
		add(w, "mcp_tools", strSeq(tools))
		if keys := errorKeys(post.op); len(keys) > 0 {
			add(w, "result_lacks", strSeq(keys))
		}
		add(m, "when", w)
		e := flow(mapping())
		add(e, "from", str("result"))
		add(e, "value", str("{"+idPath+"}"))
		if capture >= 0 {
			pn := ""
			pi := 0
			for _, sg := range post.segs {
				if isParam(sg) {
					if pi == capture {
						pn = paramName(sg)
					}
					pi++
				}
			}
			if pn != "" && reTmplSafe.MatchString(pn) {
				add(e, "container", str("{input."+pn+"}"))
			}
		}
		if resultContainer != "" {
			add(e, "container", str(resultContainer))
		}
		add(m, "extract", seq(e))
		out = append(out, m)
		g.rep.Signatures = append(g.rep.Signatures, mid)
		si := sigInfo{id: mid, kind: c.kind, post: post, idPath: idPath, errKeys: errorKeys(post.op), tools: tools, col: c, capture: capture, resultParent: strings.TrimSuffix(strings.TrimPrefix(resultContainer, "{result."), "}")}
		if len(e.Content) > 0 {
			for i := 0; i+1 < len(e.Content); i += 2 {
				if e.Content[i].Value == "container" {
					si.param = strings.TrimSuffix(strings.TrimPrefix(e.Content[i+1].Value, "{input."), "}")
				}
			}
		}
		g.sigs = append(g.sigs, si)
	}
	return out
}

// ---- rules ----

var rePublicBool = regexp.MustCompile(`^(?:is_)?(?:public|publicly_accessible|public_access|publicly_readable|allow_public_access|anonymous_access|public_read|internet_facing|open_to_public|publicly_available|public_bucket)$`)
var rePrivateBool = regexp.MustCompile(`^(?:is_)?private$`)
var reVisField = regexp.MustCompile(`^(?:visibility|access|access_level|privacy|acl|exposure|audience|sharing|access_type|public_access_level)$`)
var rePublicVal = regexp.MustCompile(`(?i)^(?:public|public[-_]read|public[-_]read[-_]write|anyone|everyone|open|internet|unauthenticated|anonymous|all_users|allusers)$`)

func (g *gen) rules(c *col) ([]*yaml.Node, []string) {
	if g.opt.NoRules {
		return nil, nil
	}
	var out []*yaml.Node
	var ids []string
	// Only attributes the kind really emits (prepare): a rule on a field the
	// kind dropped would never fire and always say not_exposed.
	for _, a := range c.attrs {
		if strings.Contains(a.field, ".") {
			continue
		}
		var exposed *yaml.Node
		want := ""
		switch {
		case a.schema.Is("boolean") && rePublicBool.MatchString(a.name):
			exposed = flow(mapping())
			add(exposed, "field", str(a.name))
			add(exposed, "equals", str("true"))
			want = "false"
		case a.schema.Is("boolean") && rePrivateBool.MatchString(a.name):
			exposed = flow(mapping())
			add(exposed, "field", str(a.name))
			add(exposed, "equals", str("false"))
			want = "true"
		case reVisField.MatchString(a.name) && len(a.schema.Enum) > 0:
			var pub, other []string
			for _, v := range a.schema.Enum {
				if rePublicVal.MatchString(v) {
					pub = append(pub, v)
				} else {
					other = append(other, v)
				}
			}
			if len(pub) == 0 || len(other) == 0 {
				continue
			}
			exposed = flow(mapping())
			add(exposed, "field", str(a.name))
			add(exposed, "in", strSeq(pub))
			want = other[0]
		default:
			continue
		}
		rid := "public_" + c.kind
		for _, x := range ids {
			if x == rid {
				rid = "public_" + c.kind + "_" + a.name
			}
		}
		ids = append(ids, rid)
		r := mapping()
		kk := add(r, "id", str(rid))
		kk.HeadComment = fmt.Sprintf("REVIEW: suggested from the %s field %q; check what it means for this API.", c.kind, a.field)
		add(r, "kind", str(c.kind))
		add(r, "severity", str("high"))
		add(r, "signal", str("api_field"))
		add(r, "exposed", exposed)
		add(r, "title", str(fmt.Sprintf("Public %s: {name}", strings.ReplaceAll(c.kind, "_", " "))))
		expl := fmt.Sprintf("%s reports %s = %s for this %s, which the API marks as publicly accessible.", g.display, a.field, describeValue(exposed), strings.ReplaceAll(c.kind, "_", " "))
		if a.schema.Description != "" {
			expl += " The API describes the field as: " + plainText(a.schema.Description, 300)
		}
		add(r, "explanation", str(expl))
		add(r, "caveat", str(fmt.Sprintf("Generated from the OpenAPI field %s; what %q means is the provider's definition.", a.field, describeValue(exposed))))
		fix := mapping()
		add(fix, "kind", str("steps"))
		text := fmt.Sprintf("Set %s to %s for this %s in %s.", a.field, want, strings.ReplaceAll(c.kind, "_", " "), g.display)
		for _, m := range []string{"patch", "put"} {
			if up := g.findOp(m, c.norm+"/{}"); up != nil && up.op.Body != nil && up.op.Body.Properties[a.field] != nil {
				text += fmt.Sprintf("\nAPI: %s %s with %s set to %s in the JSON body.", strings.ToUpper(m), g.pathText(c, up, g.itemRef(c)), a.field, want)
				break
			}
		}
		add(fix, "text", str(text))
		add(r, "fix", fix)
		out = append(out, r)
		g.rep.Rules = append(g.rep.Rules, rid)
	}
	return out, ids
}

func describeValue(pred *yaml.Node) string {
	for i := 0; i+1 < len(pred.Content); i += 2 {
		switch pred.Content[i].Value {
		case "equals":
			return pred.Content[i+1].Value
		case "in":
			var vs []string
			for _, v := range pred.Content[i+1].Content {
				vs = append(vs, v.Value)
			}
			return strings.Join(vs, " or ")
		}
	}
	return ""
}

// ---- coverage and recorder ----

func (g *gen) coverage(sel []*col) *yaml.Node {
	n := seq()
	row := func(kind, status, note string) {
		m := flow(mapping())
		add(m, "kind", str(kind))
		add(m, "status", str(status))
		add(m, "note", str(strings.Join(strings.Fields(note), " ")))
		n.Content = append(n.Content, m)
	}
	for _, c := range sel {
		status, note := "full", "GET "+c.path
		if c.paging.style != "cursor" && c.paging.style != "none" {
			status, note = "partial", note+"; first page only: "+c.paging.note
		}
		row(c.kind, status, note)
	}
	planned := 0
	for _, ki := range g.rep.Kinds {
		if !ki.Selected && planned < 40 {
			row(ki.Kind, "planned", "GET "+ki.Path+": not generated ("+ki.Note+")")
			planned++
		}
	}
	return n
}

func (g *gen) recorder(sel []*col) *yaml.Node {
	set := map[string]bool{}
	if !g.acct.none && g.acct.idF != "" {
		set[g.acct.idF] = true
		if g.acct.nameF != "" {
			set[g.acct.nameF] = true
		}
	}
	for _, c := range sel {
		set[c.idField] = true
		if n := pickName(c.item, c.idField); n != "" {
			set[n] = true
		}
		if u := pickURL(c.item); u != "" {
			set[u] = true
		}
	}
	var keys []string
	for k := range set {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	m := mapping()
	add(m, "pseudonymize", strSeq(keys))
	return m
}

// exposureField reports whether an attribute can back a public_* rule.
func exposureField(a attr) bool {
	if strings.Contains(a.field, ".") {
		return false
	}
	switch {
	case a.schema.Is("boolean") && (rePublicBool.MatchString(a.name) || rePrivateBool.MatchString(a.name)):
		return true
	case reVisField.MatchString(a.name) && len(a.schema.Enum) > 0:
		pub, other := 0, 0
		for _, v := range a.schema.Enum {
			if rePublicVal.MatchString(v) {
				pub++
			} else {
				other++
			}
		}
		return pub > 0 && other > 0
	}
	return false
}
